import { readFile } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
const file = process.argv[2];
if (!file) throw new Error('用法：node scripts/update-career-content.mjs <JSON文件> [--replace]');
const url = 'https://zijinhua.297782.xyz/v1/career-rescue/content';
const input = JSON.parse(await readFile(path.resolve(file), 'utf8'));
const read = await fetch(url, { method: 'HEAD', signal: AbortSignal.timeout(15000) });
if (!read.ok) throw new Error(`读取资料失败：${read.status}`);
const version = read.headers.get('ETag')?.match(/^(?:W\/)?"(\d+)"$/)?.[1];
if (version === undefined || !Number.isSafeInteger(Number(version))) throw new Error('资料版本无效');
const token = (process.env.OFFICIAL_PUBLISH_TOKEN || await readFile(path.join(os.homedir(), '.codex', 'zjh-official-publish-token'), 'utf8')).trim();
const result = await fetch(url, { method: process.argv.includes('--replace') ? 'PUT' : 'PATCH', headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json', 'If-Match': `"${version}"` }, body: JSON.stringify({ items: input.items, ...(input.removeIds ? { removeIds: input.removeIds } : {}) }), signal: AbortSignal.timeout(20000) });
const body = await result.json(); if (!result.ok) throw new Error(body.message || `更新失败：${result.status}`);
console.log(JSON.stringify(body));
